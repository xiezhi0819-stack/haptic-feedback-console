"""Copy the shared implementation into each standalone Arduino sketch."""
from pathlib import Path

firmware = Path(__file__).resolve().parent
shared = firmware / "libraries" / "HapticNode" / "src"
notice = "// Generated by firmware/sync_sketches.py. Edit the shared source.\n"

for side in ("left", "right"):
    sketch = firmware / f"esp32c3_{side}"
    for name in ("HapticNode.h", "HapticNode.cpp"):
        source = (shared / name).read_text(encoding="utf-8")
        (sketch / name).write_text(notice + source, encoding="utf-8")

